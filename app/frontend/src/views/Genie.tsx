import { useState } from "react";
import { post } from "../api";

const SUGGESTED = [
  "Which offices are furthest behind their spend plan?",
  "Which budget lines have more than $1M unobligated and expire in the next 90 days?",
  "What is the projected lapse by office?",
  "Which open procurements will miss their fund expiration?",
  "Show critical and high financial risk alerts",
];

type Turn = { q: string; a?: any; error?: string };

export default function Genie() {
  const [turns, setTurns] = useState<Turn[]>([]);
  const [q, setQ] = useState("");
  const [conv, setConv] = useState<string | undefined>();
  const [busy, setBusy] = useState(false);

  const ask = async (question: string) => {
    if (!question.trim()) return;
    setQ(""); setBusy(true);
    setTurns((t) => [...t, { q: question }]);
    try {
      const a = await post("/genie", { question, conversation_id: conv });
      setConv(a.conversation_id);
      setTurns((t) => t.map((x, i) => (i === t.length - 1 ? { ...x, a } : x)));
    } catch (e: any) {
      setTurns((t) => t.map((x, i) => (i === t.length - 1 ? { ...x, error: e.message } : x)));
    }
    setBusy(false);
  };

  return (
    <div className="card">
      <h2>Ask the data (Genie)</h2>
      <p className="hint">Natural-language questions over the governed gold tables and metric view. Answers respect Unity Catalog permissions.</p>
      <div className="chips" style={{ marginBottom: 14 }}>{SUGGESTED.map((s) => <button key={s} disabled={busy} onClick={() => ask(s)}>{s}</button>)}</div>
      <div className="chat">
        {turns.map((t, i) => (
          <div key={i} className="chat">
            <div className="msg user">{t.q}</div>
            <div className="msg bot">
              {t.error ? <div className="error">{t.error}</div> : !t.a ? <span className="muted">Genie is thinking…</span> : (
                <>
                  {t.a.description && <p style={{ marginTop: 0 }}>{t.a.description}</p>}
                  {t.a.text && <p style={{ marginTop: 0 }}>{t.a.text}</p>}
                  {t.a.columns.length > 0 && (
                    <div style={{ overflowX: "auto" }}>
                      <table><thead><tr>{t.a.columns.map((c: string) => <th key={c}>{c}</th>)}</tr></thead>
                        <tbody>{t.a.rows.slice(0, 25).map((r: any[], j: number) => <tr key={j}>{r.map((v, k) => <td key={k} className="small">{v}</td>)}</tr>)}</tbody></table>
                    </div>
                  )}
                  {t.a.sql && <details><summary className="small muted">SQL generated by Genie · ran as {t.a.identity}</summary><pre className="sql">{t.a.sql}</pre></details>}
                </>
              )}
            </div>
          </div>
        ))}
      </div>
      <div style={{ display: "flex", gap: 8, marginTop: 14 }}>
        <input style={{ flex: 1 }} placeholder="Ask about obligations, balances, lapse risk, procurements…" value={q}
               onChange={(e) => setQ(e.target.value)} onKeyDown={(e) => e.key === "Enter" && ask(q)} disabled={busy} />
        <button className="primary" disabled={busy} onClick={() => ask(q)}>Ask</button>
        {conv && <button className="ghost" onClick={() => { setConv(undefined); setTurns([]); }}>New conversation</button>}
      </div>
    </div>
  );
}
